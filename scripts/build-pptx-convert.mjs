// Bundles scripts/pptx-convert-entry.mjs (@hc/export's PPTX importer and page
// images design) into backend/internal/pptxconv/pptxconv.js, a single
// self-contained IIFE the Go binary embeds (go:embed) and executes under goja
// for the server-side Canva import. The output is COMMITTED, like the crdt
// fold and composer bundles, so `go build`/`go test` never depend on a Node
// toolchain. Re-run via `npm run gen:pptx-convert` after changing the
// importers (build:packages first so dist reflects the source), then
// `npm run gen:pptx-convert-fixture` if the output changed intentionally.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "scripts/pptx-convert-entry.mjs")],
  outfile: path.join(root, "backend/internal/pptxconv/pptxconv.js"),
  bundle: true,
  format: "iife",
  // goja parses ES2017-ish syntax; es2016 keeps the emitted code comfortably
  // inside what it accepts (async functions are lowered to generators).
  target: "es2016",
  platform: "neutral",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  legalComments: "none",
  banner: {
    js: "// GENERATED by scripts/build-pptx-convert.mjs - do not edit by hand.",
  },
  logLevel: "info",
});
